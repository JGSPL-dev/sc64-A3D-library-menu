# Pre-render the Library cartridge/disk art at exact framebuffer sizes, fully opaque.
# The label window is filled with the blank-label grey; label art is drawn over it at runtime.
import sys
from PIL import Image, ImageDraw
SEL=(255,255,255); TILE=(0x23,0x23,0x26); GREY=(0x8F,0x8F,0x95)
def bake(src, w, h, bg, win, name):
    im=Image.open(src).convert('RGBA'); sw,sh=im.size; S=8
    big=im.resize((sw*S,sh*S),Image.NEAREST)
    base=Image.new('RGBA',big.size,bg+(255,))
    x0,y0,ww,hh=win
    ImageDraw.Draw(base).rectangle([x0*S,y0*S,(x0+ww)*S-1,(y0+hh)*S-1],fill=GREY+(255,))
    base.alpha_composite(big)
    base.resize((w,h),Image.LANCZOS).convert('RGB').save(name)
    return (round(x0*w/sw), round(y0*h/sh), round(ww*w/sw), round(hh*h/sh))
specs=[('lib-cart.png',112,98,SEL,(38,7,74,86),'lib-cart-sel.png'),
       ('lib-cart.png',112,98,TILE,(38,7,74,86),'lib-cart-small.png'),
       ('lib-disk.png',59,80,SEL,(20,40,57,29),'lib-disk-sel.png'),
       ('lib-disk.png',59,80,TILE,(20,40,57,29),'lib-disk-small.png')]
hdr=['/* Generated by tools/bake_sprites.py: pre-scaled, opaque cartridge art and label windows (framebuffer px). */','#ifndef LIB_SPRITES_H__','#define LIB_SPRITES_H__']
for src,w,h,bg,win,name in specs:
    r=bake(src,w,h,bg,win,name)
    key=name[4:-4].upper().replace('-','_')
    hdr+= [f'#define {key}_W {w}',f'#define {key}_H {h}',f'#define {key}_WIN_X {r[0]}',f'#define {key}_WIN_Y {r[1]}',f'#define {key}_WIN_W {r[2]}',f'#define {key}_WIN_H {r[3]}']
hdr.append('#endif')
open(sys.argv[1],'w').write('\n'.join(hdr)+'\n')
