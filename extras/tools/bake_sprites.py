# Pre-render the Library cartridge/disk art at exact framebuffer sizes, fully opaque.
# The label window is filled with the blank-label grey; label art is drawn over it at runtime.
import sys
from PIL import Image, ImageDraw
SEL=(255,255,255); BODY=(0xCD,0xCD,0xD2); TILE=(0x23,0x23,0x26); GREY=(0x8F,0x8F,0x95); OUTLINE=(0x4E,0x4E,0x54)
ARCH=5      # px the window's top corners drop below its centre
BOTTOM_R=0  # bottom corners square: straight sides down from the arch
def window_mask(wx, wy, ww, wh):
    m=set(); c=(ww-1)/2
    for i in range(ww):
        top=round(ARCH*((i-c)/c)**2)
        for j in range(top, wh):
            # rounded bottom corners
            dx=min(i, ww-1-i); dy=wh-1-j
            if dx<BOTTOM_R and dy<BOTTOM_R and (BOTTOM_R-dx-0.5)**2+(BOTTOM_R-dy-0.5)**2>BOTTOM_R**2: continue
            m.add((wx+i, wy+j))
    return m
def outline_of(m):
    o=set()
    for (i,j) in m:
        for di,dj in ((1,0),(-1,0),(0,1),(0,-1)):
            if (i+di,j+dj) not in m: o.add((i+di,j+dj))
    return o
MEDIUM=(0x86,0x86,0x8C)   # selected cart: moulding lines and label outline
def darken_lines(im, m, bg):
    # Selected cart: the moulding lines go medium grey; the cart body keeps its colour.
    # Pixels on the cart's outer edge are left alone so no dark fringe appears against the card.
    src=im.copy().load(); px=im.load(); W,H=im.size
    def edge(i,j):
        for di in (-1,0,1):
            for dj in (-1,0,1):
                x,y=i+di,j+dj
                if not (0<=x<W and 0<=y<H) or src[x,y][:3]==bg: return True
        return False
    for j in range(H):
        for i in range(W):
            r,g,b,a=src[i,j]
            if a and (i,j) not in m and r<198 and (r,g,b)!=OUTLINE and not edge(i,j):
                k=max(0.0,min(1.0,(205-r)/35))
                px[i,j]=tuple(int(c*(1-k)+t*k) for c,t in zip((r,g,b),MEDIUM))+(a,)
def bake(src, w, h, bg, win, name, fixed=None, lines=False):
    im=Image.open(src).convert('RGBA'); sw,sh=im.size; S=8
    big=im.resize((sw*S,sh*S),Image.NEAREST)
    # Colour is resampled over the cart's own body colour (not the background), and the
    # silhouette is a hard mask, so the cart edge never picks up dark or light fringe pixels.
    base=Image.new('RGBA',big.size,BODY+(255,))
    x0,y0,ww,hh=win
    ImageDraw.Draw(base).rectangle([x0*S,y0*S,(x0+ww)*S-1,(y0+hh)*S-1],fill=GREY+(255,))
    base.alpha_composite(big)
    colour=base.resize((w,h),Image.BOX).convert('RGB')   # BOX: no ringing halo around edges
    alpha=big.split()[3].copy()
    if not fixed:
        # Disks keep their blank grey label window as part of the shape.
        ImageDraw.Draw(alpha).rectangle([x0*S,y0*S,(x0+ww)*S-1,(y0+hh)*S-1],fill=255)
    shape=alpha.resize((w,h),Image.BOX).point(lambda v: 255 if v>=128 else 0)
    out=Image.new('RGB',(w,h),bg); out.paste(colour,(0,0),shape)
    r=(round(x0*w/sw), round(y0*h/sh), round(ww*w/sw), round(hh*h/sh))
    if fixed:
        # Cartridges: the label window is cut out (transparent) so the label is drawn first and
        # the cart over it. The window has an arched top and rounded bottom corners, like the
        # recess on a real N64 cart, with a 1px dark 3DOS-style outline around it.
        r=fixed; out=out.convert('RGBA'); px=out.load()
        m=window_mask(*r)
        for (i,j) in m: px[i,j]=(0,0,0,0)
        for (i,j) in outline_of(m): px[i,j]=(MEDIUM if lines else OUTLINE)+(255,)
        if lines: darken_lines(out, m, bg)
        # Soften the very top edge: the two top tabs take the colour of the centre of the top row.
        for j in range(2):
            mid=px[w//2,j]
            if not mid[3]: continue
            for i in range(w):
                if px[i,j][3] and px[i,j][:3]!=bg: px[i,j]=mid
    out.save(name)
    return r
CART_WIN=(27,7,58,86)   # framebuffer px: fills the cart's label recess
specs=[('lib-cart.png',112,98,SEL,(38,7,74,86),'lib-cart-sel.png',CART_WIN,True),
       ('lib-cart.png',112,98,TILE,(38,7,74,86),'lib-cart-small.png',CART_WIN,True),
       ('lib-disk.png',59,80,SEL,(20,40,57,29),'lib-disk-sel.png',None,False),
       ('lib-disk.png',59,80,TILE,(20,40,57,29),'lib-disk-small.png',None,False)]
hdr=['/* Generated by tools/bake_sprites.py: pre-scaled, opaque cartridge art and label windows (framebuffer px). */','#ifndef LIB_SPRITES_H__','#define LIB_SPRITES_H__']
for src,w,h,bg,win,name,fixed,lines in specs:
    r=bake(src,w,h,bg,win,name,fixed,lines)
    key=name[4:-4].upper().replace('-','_')
    hdr+= [f'#define {key}_W {w}',f'#define {key}_H {h}',f'#define {key}_WIN_X {r[0]}',f'#define {key}_WIN_Y {r[1]}',f'#define {key}_WIN_W {r[2]}',f'#define {key}_WIN_H {r[3]}']
hdr.append('#endif')
open(sys.argv[1],'w').write('\n'.join(hdr)+'\n')
